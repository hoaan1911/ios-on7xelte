#!/usr/bin/env python3
"""Turn a photo into the J7 (A5XELTE) wallpaper, two ways.

There is no host-visible storage on the phone yet, so a file cannot be pushed to
/var/mobile/j7wall.raw from a computer.  What can be flashed is the BOOT
partition, so the wallpaper has to travel inside the kernel image.  This script
produces the header the kernel compiles in, and optionally the raw file for the
path form, from the same source picture.

    python3 tools/j7wall.py beach.jpg --header xnu/patches/j7wall_data.h
    python3 tools/j7wall.py beach.jpg --raw /tmp/j7wall.raw

The kernel draws the wallpaper at the logical display size (750x1334 by
default), because that is the space the desktop layer occupies.  To keep the
image small enough to carry in a boot image the header stores it at half size
(375x667) as RGB565 -- 500,250 bytes -- and the kernel doubles every pixel when
it expands it.  --scale 1 stores full size, --scale 3 a third.
"""

import argparse
import sys

try:
    from PIL import Image
except ImportError:
    sys.exit("needs Pillow: python3 -m pip install pillow")

LOGICAL = (750, 1334)          # sweetfb_lw x sweetfb_lh


def crop_to_aspect(im, aspect):
    """Centre-crop to the display aspect so nothing is squashed."""
    w, h = im.size
    if w * aspect > h:              # too wide
        new_w = int(round(h * aspect))
        x = (w - new_w) // 2
        return im.crop((x, 0, x + new_w, h))
    new_h = int(round(w / aspect))
    y = (h - new_h) // 2
    return im.crop((0, y, w, y + new_h))


def prepare(path, scale):
    im = Image.open(path).convert("RGB")
    im = crop_to_aspect(im, LOGICAL[0] / LOGICAL[1])
    size = (LOGICAL[0] // scale, LOGICAL[1] // scale)
    return im.resize(size, Image.LANCZOS)


def bgra(im):
    return im.convert("RGBA").tobytes("raw", "BGRA")


def rgb565(im):
    raw = im.tobytes()          # RGB, three bytes per pixel
    out = bytearray(len(raw) // 3 * 2)
    for i in range(0, len(raw), 3):
        v = ((raw[i + 0] & 0xF8) << 8) | ((raw[i + 1] & 0xFC) << 3) | (raw[i + 2] >> 3)
        out[i // 3 * 2] = v & 0xFF
        out[i // 3 * 2 + 1] = v >> 8
    return bytes(out)


def write_header(im, path, name):
    data = rgb565(im)
    w, h = im.size
    with open(path, "w") as f:
        f.write("/* Generated by tools/j7wall.py -- do not edit.\n")
        f.write(" * %dx%d RGB565, little endian, expanded by scaledCopy(). */\n" % (w, h))
        f.write("#define J7WALL_WIDTH  %d\n" % w)
        f.write("#define J7WALL_HEIGHT %d\n" % h)
        f.write("static const unsigned short %s[%d] = {\n" % (name, w * h))
        for i in range(0, len(data), 2):
            if i % 24 == 0:
                f.write("\n    ")
            f.write("0x%04x," % (data[i] | (data[i + 1] << 8)))
        f.write("\n};\n")


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("photo")
    ap.add_argument("--scale", type=int, default=2, choices=(1, 2, 3, 5),
                    help="store at 1/scale of the logical size (default 2)")
    ap.add_argument("--header", help="write a C header here")
    ap.add_argument("--name", default="j7wall_data", help="array name in the header")
    ap.add_argument("--raw", help="write a raw BGRA file here (for /var/mobile/j7wall.raw)")
    args = ap.parse_args()

    if not args.header and not args.raw:
        ap.error("nothing to write: pass --header and/or --raw")

    im = prepare(args.photo, args.scale)
    print("stored %dx%d (%d bytes RGB565)" % (im.size[0], im.size[1],
                                              im.size[0] * im.size[1] * 2))
    if args.header:
        write_header(im, args.header, args.name)
        print("header  %s" % args.header)
    if args.raw:
        full = im.resize(LOGICAL, Image.BICUBIC)
        data = bgra(full)
        with open(args.raw, "wb") as f:
            f.write(data)
        print("raw     %s (%d bytes BGRA)" % (args.raw, len(data)))
        if len(data) != LOGICAL[0] * LOGICAL[1] * 4:
            sys.exit("raw size is wrong: %d" % len(data))


if __name__ == "__main__":
    main()
